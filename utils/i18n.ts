export const UI_DICTIONARIES: Record<UiLang, Dictionary> = { zh, en };

export const detectInitialUiLang = (): UiLang => {
  try {
    const saved = typeof window !== 'undefined' ? window.localStorage.getItem(UI_LANG_STORAGE_KEY) : null;
    if (saved === 'zh' || saved === 'en') return saved;
  } catch {
    // Storage can be unavailable; fall back to the default language.
  }
  return 'zh';
};

export const formatUiString = (
  lang: UiLang,
  key: string,
  params?: Record<string, string | number>
) => {
  const template = UI_DICTIONARIES[lang][key] ?? UI_DICTIONARIES.zh[key] ?? key;
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name) =>
    params[name] === undefined ? match : String(params[name])
  );
};
